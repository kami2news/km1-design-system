"""KM1 B 案のアイコンを Flutter の描画コードにする / Generate Flutter painters for KM1 B icons
使い方 / Usage: python3 km1_bdart.py km1-icons.json <出力フォルダ>  → km1_icons_b.dart
原図（SVG のパス）をそのまま Dart の Path 命令に直すので、Web と同じ形になる。
SVG path data is converted command by command, so Flutter draws the same shapes as the web.
"""
import json, math, re, sys

def tokens(d):
    for m in re.finditer(r'[MmLlHhVvAaZzCcQq]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?', d):
        yield m.group(0)

def to_dart(d, var='p'):
    """SVG のパス → Dart の Path 命令（絶対座標）/ SVG path → absolute Dart Path calls"""
    t = list(tokens(d)); i = 0; out = []; x = y = sx = sy = 0.0; cmd = None
    def num():
        nonlocal i; v = float(t[i]); i += 1; return v
    def flag():
        # 弧の旗は「1 0」のように数字がくっつくことがある / arc flags may be packed
        nonlocal i
        s = t[i]
        if s in ('0', '1'): i += 1; return int(s)
        f = int(s[0]); t[i] = s[1:]; return f
    f = lambda v: ('%.3f' % v).rstrip('0').rstrip('.')
    while i < len(t):
        if re.fullmatch(r'[A-Za-z]', t[i]): cmd = t[i]; i += 1
        c = cmd; rel = c.islower(); C = c.upper()
        if C == 'Z':
            out.append(f'{var}.close();'); x, y = sx, sy; continue
        if C == 'M':
            nx, ny = num(), num()
            if rel: nx += x; ny += y
            x, y, sx, sy = nx, ny, nx, ny; out.append(f'{var}.moveTo({f(x)}, {f(y)});'); cmd = 'l' if rel else 'L'; continue
        if C == 'L':
            nx, ny = num(), num()
            if rel: nx += x; ny += y
            x, y = nx, ny; out.append(f'{var}.lineTo({f(x)}, {f(y)});'); continue
        if C == 'H':
            nx = num(); x = nx + (x if rel else 0); out.append(f'{var}.lineTo({f(x)}, {f(y)});'); continue
        if C == 'V':
            ny = num(); y = ny + (y if rel else 0); out.append(f'{var}.lineTo({f(x)}, {f(y)});'); continue
        if C == 'A':
            rx, ry, rot = num(), num(), num(); large = flag(); sweep = flag(); nx, ny = num(), num()
            if rel: nx += x; ny += y
            x, y = nx, ny
            out.append(f'{var}.arcToPoint(Offset({f(x)}, {f(y)}), radius: Radius.elliptical({f(rx)}, {f(ry)}), rotation: {f(rot)}, largeArc: {"true" if large else "false"}, clockwise: {"true" if sweep else "false"});')
            continue
        if C == 'Q':
            a = [num() for _ in range(4)]
            if rel: a = [a[0] + x, a[1] + y, a[2] + x, a[3] + y]
            x, y = a[2], a[3]; out.append(f'{var}.quadraticBezierTo({", ".join(f(v) for v in a)});'); continue
        if C == 'C':
            a = [num() for _ in range(6)]
            if rel: a = [a[0] + x, a[1] + y, a[2] + x, a[3] + y, a[4] + x, a[5] + y]
            x, y = a[4], a[5]; out.append(f'{var}.cubicTo({", ".join(f(v) for v in a)});'); continue
        raise ValueError(f'unsupported command {c} in {d}')
    return out

def main(src, outdir):
    d = json.load(open(src))
    b = {n: e for n, e in d['icons'].items() if 'b' in e}
    L = ["// KM1 B 案のアイコン（KM1-ICO-001 §8）。icons/km1_bdart.py が作る。手で直さない。",
         "// KM1 B icons, generated by icons/km1_bdart.py from the same source drawings as the web. Do not edit.",
         "// 色は km1_theme.dart の Km1Colors から直接読む（km1_widgets.dart がなくても組み込める）。",
         "// Colors come straight from Km1Colors in km1_theme.dart, so this file builds without km1_widgets.dart.",
         "import 'package:flutter/material.dart' show Theme;",
         "import 'package:flutter/widgets.dart';",
         "import 'km1_theme.dart';",
         "import 'km1_icons.dart';", "",
         "/// KM1 B 案で描くアイコンの名前 / names drawn in the KM1 B style",
         "enum Km1BIconName { " + ', '.join(re.sub(r'-(\w)', lambda m: m.group(1).upper(), n) for n in b) + " }", "",
         "/// 通常表示（Regular）は線＋淡い面で描き、filled は B 案の塗りの形（Km1Icons の …Filled の字形）を使う。",
         "/// 色は既定で icon-ink。押す・選ぶなどの状態では color に親の文字色を渡す。",
         "/// Regular draws strokes + tint; filled uses the B filled glyphs from Km1Icons. Color defaults to icon-ink; pass color for states.",
         "class Km1BIcon extends StatelessWidget {",
         "  const Km1BIcon(this.name, {super.key, this.size = 20, this.filled = false, this.color, this.inherit = false, this.semanticLabel});",
         "  final Km1BIconName name;", "  final double size;", "  final bool filled;",
         "  /// 状態の色（押す・選ぶ・無効・強い背景の上）。省くと icon-ink / state color; defaults to icon-ink", "  final Color? color;",
         "  /// 部品の中のアイコンは true にして、まわりの IconTheme の色に従う / true inside parts: follow IconTheme color", "  final bool inherit;",
         "  /// アイコンだけで意味を持つときの読み上げの名前 / label when the icon stands alone", "  final String? semanticLabel;", "",
         "  static const Map<Km1BIconName, List<IconData>> _filled = {"]
    for n in b:
        cn = re.sub(r'-(\w)', lambda m: m.group(1).upper(), n)
        L.append(f"    Km1BIconName.{cn}: [Km1Icons.{cn}16Filled, Km1Icons.{cn}Filled, Km1Icons.{cn}24Filled],")
    L += ["  };", "",
          "  @override", "  Widget build(BuildContext context) {",
          "    final c = Theme.of(context).extension<Km1Colors>() ?? Km1Colors.light;",
          "    final hc = MediaQuery.highContrastOf(context);",
          "    final ink = color ?? (inherit ? (IconTheme.of(context).color ?? c.ink) : c.iconInk);",
          "    Widget w;",
          "    if (filled) {",
          "      final g = _filled[name]!;",
          "      w = Icon(size <= 16 ? g[0] : size <= 20 ? g[1] : g[2], size: size, color: ink);",
          "    } else {",
          "      w = SizedBox.square(dimension: size, child: CustomPaint(painter: _Km1BPainter(name, size, ink,",
          "          // ハイコントラストと強い背景の上（color を渡したとき）は面を描かない / no tint in high contrast or with an explicit state color",
          "          hc || color != null ? null : [c.iconTintStart, c.iconTintEnd])));",
          "    }",
          "    return semanticLabel == null ? ExcludeSemantics(child: w) : Semantics(label: semanticLabel, image: true, child: ExcludeSemantics(child: w));",
          "  }", "}", "",
          "class _Km1BPainter extends CustomPainter {",
          "  _Km1BPainter(this.name, this.px, this.ink, this.tint);",
          "  final Km1BIconName name;", "  final double px;", "  final Color ink;", "  final List<Color>? tint;", "",
          "  @override", "  void paint(Canvas canvas, Size size) {",
          "    canvas.scale(size.width / 20);",
          "    final k = px <= 16 ? 0 : px <= 20 ? 1 : 2;",
          "    switch (name) {"]
    for n, e in b.items():
        bb = e['b']; cn = re.sub(r'-(\w)', lambda m: m.group(1).upper(), n)
        L.append(f"      case Km1BIconName.{cn}: {{")
        for ki, k in enumerate(('16', '20', '24')):
            L.append(f"        {'if' if ki == 0 else '} else if'} (k == {ki}) {{")
            if bb['tint']:
                L.append("          if (tint != null) {")
                L.append("            final t = Path()..fillType = PathFillType.nonZero;")
                L += ['            ' + s_ for s_ in to_dart(bb['tint'][k], 't')]
                L.append(f"            canvas.drawPath(t, Paint()..shader = LinearGradient(begin: Alignment.topCenter, end: Alignment.bottomCenter, colors: tint!).createShader(const Rect.fromLTRB(0, {bb['tintY'][0]}, 20, {bb['tintY'][1]})));")
                L.append("          }")
            L.append("          final s = Path()..fillType = PathFillType.nonZero;")
            L += ['          ' + s_ for s_ in to_dart(bb['ink'][k], 's')]
            L.append("          canvas.drawPath(s, Paint()..color = ink);")
        L.append("        }")
        L.append("      }")
    L += ["    }", "  }", "",
          "  @override", "  bool shouldRepaint(_Km1BPainter o) => o.name != name || o.ink != ink || o.px != px || o.tint != tint;", "}"]
    open(outdir + '/km1_icons_b.dart', 'w').write('\n'.join(L) + '\n')
    print('b icons', len(b))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
