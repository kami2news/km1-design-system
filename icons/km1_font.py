"""KM1 のアイコンを Flutter 用のアイコンフォントにする / Build the KM1 icon font and Dart class for Flutter
使い方 / Usage: python3 km1_font.py km1-icons.json <出力フォルダ>
出力 / Output: KM1Icons.ttf, km1_icons.dart
"""
import json, sys, re
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

UPM = 2000
def camel(n): p = n.split('-'); return p[0] + ''.join(x[:1].upper() + x[1:] for x in p[1:])

def main(src, out):
    data = json.load(open(src))
    order = ['.notdef']; glyphs = {}; cmap = {}; entries = []
    cp = 0xE000
    pen0 = TTGlyphPen(None); glyphs['.notdef'] = pen0.glyph()
    for name, e in data['icons'].items():
        for size, suffix in ((20, ''), (16, '16'), (24, '24')):
            for v in ('regular', 'filled'):
                gname = f'{name}_{size}_{v}'.replace('-', '_')
                k = UPM / size
                tt = TTGlyphPen(None)
                pen = Cu2QuPen(TransformPen(tt, (k, 0, 0, -k, 0, UPM * 0.875)), max_err=1.0, reverse_direction=True)
                parse_path(e['paths'][f'{size}-{v}'], pen)
                glyphs[gname] = tt.glyph(); order.append(gname); cmap[cp] = gname
                dart = camel(name) + suffix + ('Filled' if v == 'filled' else '')
                entries.append((dart, cp, e['ja'], e['en'], size, v))
                cp += 1
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (UPM, 0) for g in order})
    fb.setupHorizontalHeader(ascent=int(UPM * 0.875), descent=-int(UPM * 0.125))
    fb.setupNameTable({'familyName': 'KM1Icons', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=int(UPM * 0.875), sTypoDescender=-int(UPM * 0.125), usWinAscent=int(UPM * 0.875), usWinDescent=int(UPM * 0.125))
    fb.setupPost(); fb.save(out + '/KM1Icons.ttf')
    lines = ["// KM1 のアイコン（KM1-ICO-001）。icons/km1_font.py が作る。手で直さない。",
             "// KM1 icons, generated by icons/km1_font.py. Do not edit.",
             "// pubspec.yaml: flutter: fonts: - family: KM1Icons  fonts: - asset: fonts/KM1Icons.ttf",
             "// 形はすべて KM1 B 案（もとにした絵は Fluent System Icons、MIT, Microsoft）/ all shapes are KM1 B drawings based on Fluent System Icons (MIT)",
             "import 'package:flutter/widgets.dart';", "",
             "abstract final class Km1Icons {",
             "  static const String _family = 'KM1Icons';"]
    for dart, c, ja, en, size, v in entries:
        lines.append(f"  /// {ja} / {en}（{size}px {v}）")
        lines.append(f"  static const IconData {dart} = IconData(0x{c:04X}, fontFamily: _family);")
    for old, new in data.get('aliases', {}).items():
        for suf in ('', '16', '24'):
            for fl in ('', 'Filled'):
                lines.append(f"  @Deprecated('{camel(new)}{suf}{fl} を使う / use {camel(new)}{suf}{fl}')")
                lines.append(f"  static const IconData {camel(old)}{suf}{fl} = {camel(new)}{suf}{fl};")
    lines.append("}")
    open(out + '/km1_icons.dart', 'w').write('\n'.join(lines) + '\n')
    print('glyphs', len(order) - 1)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
